/// The glyph bitmap data, in `GLYPH_ORDER` order.
pub fn glyph_rows() -> impl Iterator<Item = (char, [u8; 7])> {
    GLYPHS.iter().copied()
}

/// `font.json` content: char → source rect (5x7 at scale 1).
pub fn font_metadata() -> String {
    let mut glyphs = serde_json::Map::new();
    for (i, (ch, _)) in GLYPHS.iter().enumerate() {
        glyphs.insert(ch.to_string(), json!([i * 5, 0, 5, 7]));
    }
    json!({ "glyphs": glyphs }).to_string()
}

/// The font atlas PNG bytes (all glyphs packed horizontally, 5x7 each).
pub fn builtin_font() -> Result<Vec<u8>, AssetError> {
    let frames: Vec<serde_json::Value> = GLYPHS
        .iter()
        .map(|(_, glyph)| {
            let rows: Vec<String> = glyph
                .iter()
                .map(|row| {
                    (0..5)
                        .map(|col| {
                            if row & (0b10000 >> col) != 0 {
                                '#'
                            } else {
                                '.'
                            }
                        })
                        .collect()
                })
                .collect();
            json!({ "rows": rows })
        })
        .collect();
    let map = json!({
        "palette": { ".": null, "#": "#FFFFFF" },
        "frames": frames,
        "scale": 1,
    })
    .to_string();
    let pm = parse_pixel_map(&map)?;
    let atlas = build_atlas(&pm)?;
    atlas.encode_png()
}
